-- Apply with psql to the dedicated authentication database before public startup.
-- Static product catalog remains a separately packaged, read-only SQLite file.
CREATE TABLE IF NOT EXISTS organizations (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name TEXT NOT NULL, status TEXT NOT NULL DEFAULT 'pending', created_at TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS users (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 organization_id BIGINT REFERENCES organizations(id), email TEXT NOT NULL UNIQUE,
 password_hash TEXT NOT NULL, role TEXT NOT NULL DEFAULT 'member',
 status TEXT NOT NULL DEFAULT 'pending', email_verified INTEGER NOT NULL DEFAULT 0,
 failed_login_count INTEGER NOT NULL DEFAULT 0, locked_until TEXT,
 created_at TEXT NOT NULL, approved_at TEXT
);
CREATE TABLE IF NOT EXISTS licenses (
 organization_id BIGINT PRIMARY KEY REFERENCES organizations(id),
 seats INTEGER NOT NULL CHECK (seats > 0), expires_at TEXT NOT NULL,
 status TEXT NOT NULL DEFAULT 'active', updated_at TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS sessions (
 token_hash TEXT PRIMARY KEY, user_id BIGINT NOT NULL REFERENCES users(id),
 created_at TEXT NOT NULL, expires_at TEXT NOT NULL, revoked_at TEXT
);
CREATE TABLE IF NOT EXISTS remember_sessions (
 token_hash TEXT PRIMARY KEY, user_id BIGINT NOT NULL REFERENCES users(id),
 created_at TEXT NOT NULL, expires_at TEXT NOT NULL, revoked_at TEXT
);
CREATE TABLE IF NOT EXISTS pdf_download_tickets (
 token_hash TEXT PRIMARY KEY, user_id BIGINT NOT NULL REFERENCES users(id),
 part_number TEXT NOT NULL, expires_at TEXT NOT NULL, used_at TEXT
);
CREATE TABLE IF NOT EXISTS admin_mfa (
 user_id BIGINT PRIMARY KEY REFERENCES users(id), enabled_at TEXT NOT NULL,
 last_counter BIGINT NOT NULL
);
CREATE TABLE IF NOT EXISTS password_reset_tokens (
 token_hash TEXT PRIMARY KEY, user_id BIGINT NOT NULL REFERENCES users(id),
 created_at TEXT NOT NULL, expires_at TEXT NOT NULL, used_at TEXT
);
CREATE TABLE IF NOT EXISTS email_verification_tokens (
 token_hash TEXT PRIMARY KEY, user_id BIGINT NOT NULL REFERENCES users(id),
 created_at TEXT NOT NULL, expires_at TEXT NOT NULL, used_at TEXT
);
CREATE TABLE IF NOT EXISTS audit_logs (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 occurred_at TEXT NOT NULL, actor_user_id BIGINT REFERENCES users(id),
 organization_id BIGINT REFERENCES organizations(id), action TEXT NOT NULL,
 target_type TEXT, target_id TEXT, details_json TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS sessions_user_active_idx ON sessions(user_id, expires_at) WHERE revoked_at IS NULL;
CREATE INDEX IF NOT EXISTS audit_logs_occurred_idx ON audit_logs(occurred_at);
